def typecheck_and_resolve(srcfile: SrcFile) -> hir.AST:
    # set up the base type system/builtins
    type_system = ty.TypeSystem()
    builtins.apply_builtin_promote_rules(type_system)
    declarations = ChainMap(builtins.builtin_types)
    
    ctx = Context(srcfile, declarations, type_system)
    block = p0.parse(srcfile)
    return tcr_block(block, ctx=ctx)

def try_in_comprehension(f:Callable, *args, **kwargs):
    """allow exception-raising functions to be used in comprehensions by capturing the exception as a value rather than raising it upwards"""
    try:
        return f(*args, **kwargs)
    except Exception as e:
        return e

def typecheck_and_resolve_inner(ast: p0.AST, *, ctx: Context, type_block:bool=False) -> hir.AST:
    match ast:
        case p0.Ambiguous(candidates=candidates):
            passes = [try_in_comprehension(typecheck_and_resolve_inner, candidate, ctx=ctx, type_block=type_block) for candidate in candidates]
            passes = [p for p in passes if not isinstance(p, (ValueError, ReportException))] #TODO: filter for only exceptions that can be generated by typecheck process
            errors = [p for p in passes if isinstance(p, Exception)]
            assert len(errors) == 0, f'INTERNAL ERROR: Ambiguous AST {ast} produced {len(errors)} non-typechecking-related errors: {errors=}. {passes=}'
            if len(passes) == 0:
                # TODO: full user error report
                raise ValueError(f'USER ERROR: Ambiguous AST {ast} has no valid options: {passes=}. {ast=}')
            if len(passes) > 1:
                # TODO: full user error report
                raise ValueError(f'USER ERROR: Ambiguous AST {ast} has too many valid options that could not be disambiguated: {passes=}. {ast=}')
            return passes[0]

        
        case p0.KeywordExpr(parts=[t1.Keyword(name='let'|'const'), *_]):
            return tcr_declare(ast, ctx=ctx)

        case p0.KeywordExpr(parts=[t1.Keyword(name='import'|'from'), *_]):
            return tcr_import(ast, ctx=ctx)
        
        case p0.KeywordExpr(parts=[t1.Keyword(name='return'), *_]):
            return tcr_return(ast, ctx=ctx)

        # etc. keyword cases as outlined in t2
        # final catch-all case (internal error since t2 shouldn't produce anything like this)
        case p0.KeywordExpr():
            pdb.set_trace()
            raise ValueError(f'NOT IMPLEMENTED -OR- INTERNAL ERROR: unrecognized keyword expression structure: {ast=}')

        case p0.BinOp(op=t1.Operator(symbol=':='|'='|'::')):
            return tcr_assign(ast, ctx=ctx)

        case p0.Block(): return tcr_block(ast, ctx=ctx)
        case p0.BinOp(): return tcr_binop(ast, ctx=ctx, type_block=type_block)
        case p0.Atom(item=t1.Identifier(name='..')): return hir.Range(ast.item.loc, 'range', bounds=None, step_pair=None, left=None, right=None)
        case p0.Atom(item=t1.Identifier()): return tcr_identifier(ast.item, ctx=ctx)
        case p0.Atom(item=t1.String(content=content)): return hir.String(ast.item.loc, 'string', content)
        case p0.Atom(item=t1.Integer(value=value)): return hir.Integer(ast.item.loc, 'int', value.prefix, t0.parse_integer(value.src, value.prefix))
        # case p0.Atom(item=t1.Real()): ...
        # case p0.Atom(item=t1.BasedString()): ...
        # case p0.Atom(item=t1.Semicolon()): ...
        # case p0.Atom(item=t1.Metatag()): ...
        # case p0.Atom(item=t1.Integer()): ...
        case p0.Atom(item=t1.Bool(value=value)): return hir.Bool(ast.item.loc, 'bool', value)
        # case p0.Atom(item=t2.OpFn()): ...
        # case p0.Atom(item=t2.Placeholder()): ...
        case p0.Flat(op=t2.RangeJuxtapose()): return tcr_bare_range(ast, ctx=ctx)
        case _:
            pdb.set_trace()
            raise NotImplementedError(f'typecheck_and_resolve_inner not implemented for {type(ast)}')


