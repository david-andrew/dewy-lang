def tcr_return(ast: p0.KeywordExpr, *, ctx: Context) -> hir.AST:
    if len(ast.parts) > 2: raise ValueError(f'INTERNAL ERROR: return statement may only contain zero or one expression, got {len(ast.parts)}. {ast.parts=}. (should have been caught during p0 phase)')
    if len(ast.parts) == 1:
        return hir.Return(ast.parts[0].loc, ty.VOID_TYPE)
    item = typecheck_and_resolve_inner(ast.parts[1], ctx=ctx)
    return hir.Return(ast.parts[0].loc, ty.VOID_TYPE, item)

def tcr_block(block: p0.Block, *, ctx: Context) -> hir.AST:
    # TODO: if kind=='<>' then typecheck and resolve needs to behave differently, e.g. because `|` means `type union`, not regular `or`
    # scoped = block.kind == '{}' #TODO: would need to make a nested scope/context for this...

    # open a new scope if the block is a scoped block
    type_block = block.kind == '<>'
    if block.kind == '{}': ctx = replace(ctx, declarations=ctx.declarations.new_child())

    # typecheck and resolve the inner items
    results = [typecheck_and_resolve_inner(item, ctx=ctx, type_block=type_block) for item in block.inner]

    match block.kind:
        case '()':
            if len(results) > 1:
                return hir.Block(block.loc, results, scoped=False)
            if len(results) == 1:
                item = results[0]
                if isinstance(item, hir.Range) and item.bounds is None:
                    return replace(item, loc=block.loc, bounds=block.kind)
                return item
            return hir.Void(block.loc)
        
        case '{}':
            if len(results) > 1:
                pdb.set_trace()
                return hir.Block(block.loc, ty.BlockType, results, scoped=True) #TODO: parameterize block type based on inner content... e.g. tuple of types
            if len(results) == 1:
                return hir.Block(block.loc, results[0].type, results, scoped=True)
            return hir.Void(block.loc)

        case '[]':
            if len(results) == 1 and isinstance(results[0], hir.Range) and results[0].bounds is None:
                return replace(results[0], loc=block.loc, bounds=block.kind)
            # otherwise it may be an array. also arrays should handle multi-dimensions via spacing, nested arrays, ;, etc.
            # might also be a generator...
            pdb.set_trace()
        case '[)':
            if len(results) != 1 or not isinstance(results[0], hir.Range) or results[0].bounds is not None:
                # TODO: full user error report
                raise ValueError(f'USER ERROR: [) delimiter for range may only contain one (bare range) expression, got {len(results)}. {results=}')
            return replace(results[0], loc=block.loc, bounds=block.kind)
        case '(]':
            if len(results) != 1 or not isinstance(results[0], hir.Range) or results[0].bounds is not None:
                # TODO: full user error report
                raise ValueError(f'USER ERROR: (] delimiter for range may only contain one (bare range) expression, got {len(results)}. {results=}')
            return replace(results[0], loc=block.loc, bounds=block.kind)
        case '<>':
            # return hir.TypeBlock(block.loc, type..., results) #TODO: handling type of type block based on contained inner items
            pdb.set_trace()
        case _:
            # unreachable
            raise ValueError(f'INTERNAL ERROR: invalid block kind: {block.kind}')
        
    # unreachable 
    pdb.set_trace()

