#!/usr/bin/env python3
"""Regenerate the terminal column-width tables of compiler/utf8_text.dewy and its frozen twin utf8_text.jo.

A wcwidth-style rule, from Python's unicodedata (the Unicode version it ships is written into the files):
  zero columns: marks (Mn, Me), format characters (Cf), anything with a combining class, and the C1 controls
    (the soft hyphen U+00AD is the exception: terminals draw it, one column);
  two columns: East Asian Wide and Fullwidth (every character with emoji presentation is Wide);
  otherwise one. ASCII is one column and is not in the tables.

Usage: python3 tools/gen_utf8_width.py [--check]    (--check only verifies that the files are current)
"""
import sys
import unicodedata as ud
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BEGIN = '# width tables begin'
END = '# width tables end'


def is_zero(c):
    ch = chr(c)
    if c == 0xAD:
        return False
    return ud.category(ch) in ('Mn', 'Me', 'Cf') or ud.combining(ch) != 0 or 0x80 <= c <= 0x9F


def is_wide(c):
    return ud.east_asian_width(chr(c)) in ('W', 'F')


def ranges(pred):
    """The inclusive ranges of non-ASCII code points (not surrogates) where pred holds."""
    out, lo = [], None
    for c in range(0x80, 0x110000):
        ok = not 0xD800 <= c <= 0xDFFF and pred(c)
        if ok and lo is None:
            lo = c
        elif not ok and lo is not None:
            out.append((lo, c - 1))
            lo = None
    if lo is not None:
        out.append((lo, 0x10FFFF))
    return out


def rows(table, sep):
    values = [f'0x{v:X}' for pair in table for v in pair]
    lines, line = [], ''
    for value in values:
        if len(line) + len(value) > 100:
            lines.append(line)
            line = ''
        line += (sep if line else '') + value
    lines.append(line)
    return lines


def block(dewy):
    zero, wide = ranges(is_zero), ranges(is_wide)
    out = [f'{BEGIN} (generated by tools/gen_utf8_width.py from Unicode {ud.unidata_version}; ranges of lo hi)']
    for name, table in (('UTF8_ZERO', zero), ('UTF8_WIDE', wide)):
        if dewy:
            out.append(f'let {name}:array<int64>=[')
            out += ['    ' + line for line in rows(table, '  ')]
            out.append(']')
        else:
            out.append(f'{name} = [')
            out += ['    ' + line + ',' for line in rows(table, ', ')]
            out[-1] = out[-1][:-1]
            out.append(']')
    out.append(END)
    return '\n'.join(out)


def main():
    check = '--check' in sys.argv[1:]
    stale = False
    for name, dewy in (('compiler/utf8_text.dewy', True), ('compiler/utf8_text.jo', False)):
        path = ROOT / name
        text = path.read_text()
        start, stop = text.index(BEGIN), text.index(END) + len(END)
        new = text[:start] + block(dewy) + text[stop:]
        if new != text:
            stale = True
            if not check:
                path.write_text(new)
    if check and stale:
        sys.exit('width tables are out of date: run python3 tools/gen_utf8_width.py')


if __name__ == '__main__':
    main()
